#!/usr/bin/env python3
"""
Turns the OVF exported from the generalised build VM into the Holodeck Portal OVA: neutral names, the deployment
properties (delivered to the guest as guestinfo.ovfEnv, read by firstboot.py), a SHA-256 manifest, OVA packaging.

Usage: build-ova.py <exported-ovf-dir> <version> <output.ova>
"""
import hashlib, os, re, sys, tarfile
from xml.sax.saxutils import escape

src, version, out = sys.argv[1], sys.argv[2], sys.argv[3]
ovf_name = next(f for f in os.listdir(src) if f.endswith('.ovf'))
base = ovf_name[:-4]
text = open(os.path.join(src, ovf_name), encoding='utf-8').read()

def prop(key, label, desc, typ='string', value='', password=False, qualifiers=None):
    q = f' ovf:qualifiers="{qualifiers}"' if qualifiers else ''
    pw = ' ovf:password="true"' if password else ''
    return (f'      <Property ovf:key="{key}" ovf:type="{typ}" ovf:userConfigurable="true" ovf:value="{escape(value)}"{pw}{q}>\n'
            f'        <Label>{escape(label)}</Label>\n        <Description>{escape(desc)}</Description>\n      </Property>\n')

product = (
    '    <ProductSection ovf:required="false">\n'
    '      <Info>Holodeck Portal appliance settings</Info>\n'
    '      <Product>Holodeck Portal</Product>\n'
    '      <Vendor>Holodeck Portal (community project, not an official Broadcom product)</Vendor>\n'
    f'      <Version>{version}</Version>\n'
    f'      <FullVersion>{version}</FullVersion>\n'
    '      <Category>Network</Category>\n'
    + prop('hostname', 'Hostname', 'Short hostname of the appliance.', value='holodeck-portal')
    + prop('domain', 'DNS domain', 'DNS domain of the appliance, e.g. example.com.')
    + prop('ip', 'IPv4 address', 'Static IPv4 address. Leave empty to use DHCP.')
    + prop('prefix', 'Prefix length', 'Network prefix length for the static address, e.g. 24.', value='24')
    + prop('gateway', 'Gateway', 'Default gateway for the static address.')
    + prop('dns', 'DNS servers', 'Comma-separated DNS servers.')
    + prop('ntp', 'NTP servers', 'Comma-separated NTP servers.', value='pool.ntp.org')
    + '      <Category>Portal</Category>\n'
    + prop('portal_fqdn', 'Portal DNS name', 'The name users open in their browser (certificate and sign-in URLs). Defaults to hostname.domain.')
    + prop('admin_password', 'Portal administrator password', "Password of the portal's first administrator, user 'admin' (at least 10 characters).", password=True, qualifiers='MinLen(10)')
    + '      <Category>System</Category>\n'
    + prop('root_password', 'Root password', 'Password of the appliance root account (console and SSH).', password=True, qualifiers='MinLen(8)')
    + prop('ssh_enabled', 'Enable SSH', 'Allow SSH to the appliance.', typ='boolean', value='True')
    + '    </ProductSection>\n'
)
annotation = ('    <AnnotationSection ovf:required="false">\n      <Info>A human-readable annotation</Info>\n'
              f'      <Annotation>Holodeck Portal {version}: self-service portal for Holodeck labs on a fleet of Holorouters. '
              'Community project, not an official Broadcom product. Photon OS 5 appliance.</Annotation>\n    </AnnotationSection>\n')

text = re.sub(r'<!--Generated by[^>]*-->\n', '', text)
text = text.replace(f'ovf:id="{base}"', 'ovf:id="holodeck-portal"').replace(f'<Name>{base}</Name>', '<Name>holodeck-portal</Name>')
text = re.sub(r'<vssd:VirtualSystemIdentifier>[^<]*</vssd:VirtualSystemIdentifier>', '<vssd:VirtualSystemIdentifier>holodeck-portal</vssd:VirtualSystemIdentifier>', text)
text = re.sub(r'<Network ovf:name="[^"]*">\s*<Description>[^<]*</Description>',
              '<Network ovf:name="Management Network">\n      <Description>The network users and the Holorouters reach the portal on</Description>', text)
text = re.sub(r'<rasd:Connection>[^<]*</rasd:Connection>', '<rasd:Connection>Management Network</rasd:Connection>', text)
text = text.replace('<VirtualHardwareSection>', '<VirtualHardwareSection ovf:transport="com.vmware.guestInfo">', 1)
# One annotation (Photon's own is replaced), then the properties, ahead of the hardware section.
text = re.sub(r'\s*<AnnotationSection[^>]*>.*?</AnnotationSection>', '', text, flags=re.S)
text = re.sub(r'\s*<ProductSection[^>]*>.*?</ProductSection>', '', text, flags=re.S)
text = text.replace('    <VirtualHardwareSection', annotation + product + '    <VirtualHardwareSection', 1)
text = re.sub(r'(<rasd:ElementName>)(\d+) virtual CPU\(s\)', r'\g<1>\2 virtual CPU(s)', text)

# Files renamed after the product, references and manifest updated.
names = {}
for f in sorted(os.listdir(src)):
    if f.startswith(base) and not f.endswith(('.ovf', '.mf')):
        names[f] = 'holodeck-portal-' + version + f[len(base):]
for old, new in names.items():
    text = text.replace(f'ovf:href="{old}"', f'ovf:href="{new}"')
new_ovf = f'holodeck-portal-{version}.ovf'
work = out + '.d'
os.makedirs(work, exist_ok=True)
open(os.path.join(work, new_ovf), 'w', encoding='utf-8').write(text)
for old, new in names.items():
    dst = os.path.join(work, new)
    if os.path.exists(dst):
        os.remove(dst)
    os.link(os.path.join(src, old), dst)

def sha256(p):
    h = hashlib.sha256()
    with open(p, 'rb') as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()

order = [new_ovf] + list(names.values())
mf = f'holodeck-portal-{version}.mf'
open(os.path.join(work, mf), 'w').write(''.join(f'SHA256({n})= {sha256(os.path.join(work, n))}\n' for n in order))
with tarfile.open(out, 'w', format=tarfile.USTAR_FORMAT) as t:
    for n in [new_ovf, mf] + list(names.values()):
        info = t.gettarinfo(os.path.join(work, n), arcname=n)
        info.uid = info.gid = 64
        info.uname = info.gname = 'someone'
        with open(os.path.join(work, n), 'rb') as fh:
            t.addfile(info, fh)
print(f'{out}: {os.path.getsize(out) / 1024**3:.2f} GB, SHA-256 {sha256(out)}')
